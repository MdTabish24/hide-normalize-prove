"""Write docker-compose.pinned.auto.yml: give Red, the gateway and the Blue side separate CPU cores for THIS host (cgroup cpuset).

    python pin_cpus.py              # detect the CPUs Docker can use and write the overlay
    python pin_cpus.py --ncpu 4     # plan for a 4-CPU host (for tests)
    python pin_cpus.py --up         # write the overlay, then: docker compose -f docker-compose.yml -f docker-compose.pinned.auto.yml up -d --build

Why: a Red flood inside its own container shared CPU cores with the gateway, which moved Blue's release times (attack 9c). With separate cores the shift was
not found in the measured run. The fixed overlay `docker-compose.pinned.yml` needs 8 CPUs; this plan scales down and does nothing below 4 CPUs (no pinning, a warning).
Pinning is opt-in (it changes where processes run, not what they compute) and is not a claim of hardware isolation.
"""
import argparse
from pathlib import Path
import subprocess
import sys

OVERLAY = Path(__file__).resolve().parent / "docker-compose.pinned.auto.yml"
SERVICES = ("red-client", "gateway", "operator-proxy", "blue-defense", "model-mock", "audit-collector")


def cores(first, last):
    return str(first) if first == last else f"{first}-{last}"


def plan(ncpu):
    """Return {service: cpuset} for a host with ncpu CPUs, or {} when there are too few to separate Red from the gateway."""
    if ncpu >= 8:  # the layout of docker-compose.pinned.yml
        return {"red-client": "0-1", "gateway": "2-3", "operator-proxy": "4", "blue-defense": "5", "model-mock": "6", "audit-collector": "7"}
    if ncpu >= 4:  # Red alone on core 0, the gateway alone on core 1, everything else shares the remaining cores
        rest = cores(2, ncpu - 1)
        return {"red-client": "0", "gateway": "1", "operator-proxy": rest, "blue-defense": rest, "model-mock": rest, "audit-collector": rest}
    return {}


def docker_cpus():
    out = subprocess.run(["docker", "info", "--format", "{{.NCPU}}"], capture_output=True, text=True, timeout=60).stdout.strip()
    return int(out)


def write(ncpu):
    layout = plan(ncpu)
    lines = [f"# Generated by pin_cpus.py for a host with {ncpu} CPUs. Do not edit; rerun the script.", "services:" if layout else "services: {}"]
    for service in SERVICES:
        if service in layout:
            lines += [f"  {service}:", f'    cpuset: "{layout[service]}"']
    OVERLAY.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return layout


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--ncpu", type=int, help="plan for this many CPUs instead of asking Docker")
    parser.add_argument("--up", action="store_true", help="also start the stack with the overlay")
    args = parser.parse_args()
    ncpu = args.ncpu or docker_cpus()
    layout = write(ncpu)
    if not layout:
        print(f"Only {ncpu} CPUs visible to Docker: no pinning written (Red and the gateway would have to share a core).", file=sys.stderr)
    else:
        print(f"{ncpu} CPUs: " + ", ".join(f"{s}={c}" for s, c in layout.items()))
    if args.up:
        sys.exit(subprocess.call(["docker", "compose", "-f", "docker-compose.yml", "-f", OVERLAY.name, "up", "-d", "--build"], cwd=OVERLAY.parent))


if __name__ == "__main__":
    main()
